"""Build Claude Code subagents from office/roster.toml.

Reads the roster, checks it, and writes:
  .claude/agents/<role-id>.md   one subagent per role (except the main Office Manager)
  office/directory.md           a readable who's-who

Run from the repo root:  python3 tools/build_agents.py
Only files this script generated are ever overwritten or removed.
"""

from __future__ import annotations

import pathlib
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
ROSTER = ROOT / "office" / "roster.toml"
AGENTS = ROOT / ".claude" / "agents"
DIRECTORY = ROOT / "office" / "directory.md"
MARKER = "<!-- generated by tools/build_agents.py; edit office/roster.toml instead -->"
MODELS = {"opus", "sonnet", "haiku", "inherit"}
STATUSES = {"now", "later", "retired"}


def load() -> dict:
    with ROSTER.open("rb") as f:
        return tomllib.load(f)


def check(r: dict) -> list[str]:
    """Return every problem in the roster; empty means it is consistent."""
    errors = []
    skills = r.get("skills", {})
    presets = r.get("presets", {})
    roles = [role for d in r["departments"] for role in d["roles"]]
    ids = [role["id"] for role in roles]
    for dup in {i for i in ids if ids.count(i) > 1}:
        errors.append(f"role id used twice: {dup}")
    known = set(ids)
    for s in r.get("company_skills", []):
        if s not in skills:
            errors.append(f"company skill not defined: {s}")
    for d in r["departments"]:
        for s in d.get("skills", []):
            if s not in skills:
                errors.append(f"{d['id']}: department skill not defined: {s}")
        for role in d["roles"]:
            where = role["id"]
            for s in role["skills"]:
                if s not in skills:
                    errors.append(f"{where}: skill not defined: {s}")
            if role["preset"] not in presets:
                errors.append(f"{where}: unknown preset {role['preset']}")
            if role["model"] not in MODELS:
                errors.append(f"{where}: model must be one of {sorted(MODELS)}")
            if role["status"] not in STATUSES:
                errors.append(f"{where}: status must be one of {sorted(STATUSES)}")
            for h in role.get("hands_off_to", []):
                if h not in known:
                    errors.append(f"{where}: hands_off_to unknown role {h}")
    return errors


def skill_block(sid: str, s: dict, level: str = "###") -> str:
    steps = "\n".join(f"{i}. {step}" for i, step in enumerate(s["steps"], 1))
    gate = f"\n**Approval gate:** {s['gate']}. Stop before this action and return `GATE:`." if s["gate"] else ""
    return (
        f"{level} `{sid}`\n{s['does']}.\n\n"
        f"**Runs when:** {s['when']}\n\n{steps}\n\n**Output:** `{s['output']}`{gate}\n"
    )


def agent_file(r: dict, dept: dict, role: dict) -> str:
    skills = r["skills"]
    preset = r["presets"][role["preset"]]
    tools = preset["tools"] + preset.get("extra_tools", [])
    triggers = "; ".join(skills[s]["when"] for s in role["skills"])
    later = "[Not hired yet: use only if the Office Manager says so] " if role["status"] == "later" else ""
    description = f"{later}{role['one']}. Use for: {triggers}".replace("\n", " ")
    names = {x["id"]: x["name"] for d in r["departments"] for x in d["roles"]}
    handoff = ", ".join(f"{names[h]} (`{h}`)" for h in role.get("hands_off_to", []))

    own = "\n".join(skill_block(s, skills[s]) for s in role["skills"])
    dept_sk = "\n".join(skill_block(s, skills[s]) for s in dept.get("skills", [])) or "None.\n"
    comp_sk = "\n".join(skill_block(s, skills[s]) for s in r.get("company_skills", []))

    return f"""---
name: {role['id']}
description: {description}
tools: {', '.join(tools)}
model: {role['model']}
---
{MARKER}

# {role['name']}

**Department:** {dept['name']} · **Status:** {role['status']} · **Permissions:** `{role['preset']}`: {preset['note']}

You do one thing: **{role['one']}.**

## How you work
The Office Manager calls you with a task folder (for example `out/2026-01-31-fix-login/`).

1. Read `brain/rules.md` and `brain/glossary.md`, then `task.toml` and `log.md` in the task folder.
2. Do only your one thing. If part of the task belongs to someone else, say who in `NEXT:`.
3. Write your outputs into the task folder unless your skill names another place.
4. Never run an action that has an approval gate. Stop and return a `GATE:` line saying exactly what you would do.
5. Never guess. Put open questions under `QUESTIONS:`.
6. Say where every number came from.
7. Git work lands on `{r['company'].get('integration_branch', 'develop')}`. `main` only when the user asks.

End every reply with this block:

```
RESULT: done | not done | blocked
OUTPUTS: <files you wrote>
GATE: <exact action waiting for approval, or none>
QUESTIONS: <numbered, or none>
NEXT: <role id that should take it next, or none>
```

**Usually hands off to:** {handoff or 'the Office Manager'}
**Tools:** {role.get('tools_note', '')}

## Your skills
{own}
## {dept['name']} skills (shared by the department)
{dept_sk}
## Company skills (everyone)
{comp_sk}"""


def directory(r: dict) -> str:
    lines = [f"# {r['company']['name']}: who's who\n", MARKER, ""]
    for d in r["departments"]:
        lines.append(f"## {d['name']}\n{d['about']}\n")
        lines.append("| Role | Id | Status | One thing | Skills |\n|---|---|---|---|---|")
        for role in d["roles"]:
            tag = "main session" if role.get("main") else role["status"]
            lines.append(
                f"| {role['name']} | `{role['id']}` | {tag} | {role['one']} | "
                + ", ".join(f"`{s}`" for s in role["skills"]) + " |"
            )
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    r = load()
    errors = check(r)
    if errors:
        print("Roster has problems; nothing was written:")
        for e in errors:
            print("  -", e)
        return 1

    AGENTS.mkdir(parents=True, exist_ok=True)
    written = set()
    for d in r["departments"]:
        for role in d["roles"]:
            if role.get("main") or role["status"] == "retired":
                continue
            path = AGENTS / f"{role['id']}.md"
            path.write_text(agent_file(r, d, role), encoding="utf-8")
            written.add(path.name)

    removed = []
    for path in AGENTS.glob("*.md"):
        if path.name not in written and MARKER in path.read_text(encoding="utf-8"):
            path.unlink()
            removed.append(path.name)

    DIRECTORY.write_text(directory(r), encoding="utf-8")
    roles = [x for d in r["departments"] for x in d["roles"]]
    print(f"{len(roles)} roles: Office Manager (main session) + {len(written)} agents in .claude/agents/ "
          f"({sum(x['status'] == 'later' for x in roles)} of them not hired yet)")
    if removed:
        print("Removed agents no longer in the roster:", ", ".join(removed))
    print("Directory: office/directory.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
